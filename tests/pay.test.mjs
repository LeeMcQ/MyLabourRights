// Payment unlock must be server-verified (stress test 2026-11: ?paid=1 unlocked cases).
import { createRequire } from 'module'; import crypto from 'crypto'; import fs from 'fs';
const require = createRequire(import.meta.url);
const notify = require('../netlify/functions/pay-notify.js').handler;
const status = require('../netlify/functions/pay-status.js').handler;
const mem = new Map(); const store = { get: async k => mem.get(k) ?? null, setJSON: async (k, v) => mem.set(k, v) };
process.env.PAYFAST_PASSPHRASE = 'pp'; process.env.PAYFAST_MERCHANT_ID = '100';
const sign = d => crypto.createHash('md5').update(Object.keys(d).map(k => `${k}=${encodeURIComponent(d[k]).replace(/%20/g,'+')}`).join('&') + '&passphrase=pp').digest('hex');
const body = d => Object.keys(d).map(k => `${k}=${encodeURIComponent(d[k])}`).join('&');
let fail = 0; const t = (c, m) => { console.log((c ? '  ✅ ' : '  ❌ ') + m); if (!c) fail++; };
mem.set('case_1', { paid: false, amount: 199 });
const base = { merchant_id: '100', m_payment_id: 'case_1', payment_status: 'COMPLETE', amount_gross: '199.00' };
await notify({ httpMethod: 'POST', body: body(base) }, {}, { store, validate: async () => true });
t(!mem.get('case_1').paid, 'unsigned ITN rejected');
await notify({ httpMethod: 'POST', body: body({ ...base, signature: 'x' }) }, {}, { store, validate: async () => true });
t(!mem.get('case_1').paid, 'bad signature rejected');
const low = { ...base, amount_gross: '1.00' };
await notify({ httpMethod: 'POST', body: body({ ...low, signature: sign(low) }) }, {}, { store, validate: async () => true });
t(!mem.get('case_1').paid, 'wrong amount rejected');
await notify({ httpMethod: 'POST', body: body({ ...base, signature: sign(base) }) }, {}, { store, validate: async () => false });
t(!mem.get('case_1').paid, 'failed PayFast postback rejected');
await notify({ httpMethod: 'POST', body: body({ ...base, signature: sign(base) }) }, {}, { store, validate: async () => true });
t(mem.get('case_1').paid === true, 'valid ITN marks paid');
const r = await status({ queryStringParameters: { caseId: 'case_1' } }, {}, { store });
t(JSON.parse(r.body).paid === true, 'pay-status reports paid');
const r2 = await status({ queryStringParameters: { caseId: 'nope' } }, {}, { store });
t(JSON.parse(r2.body).paid === false, 'unknown case unpaid');
const html = fs.readFileSync(new URL('../public/index.html', import.meta.url), 'utf8');
t(!/params\.get\('paid'\)\s*===\s*'1'/.test(html), "index.html no longer trusts ?paid=1");
if (fail) process.exit(1);
